package com.blacklab.app

import com.blacklab.app.bh.Library
import com.blacklab.app.ui.theme.AccentPalette
import com.blacklab.app.ui.theme.LightStyle
import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File

/**
 * The web app (desktop/web, published on GitHub Pages) draws its palettes, light styles and the
 * Behavioral Health reference library from desktop/web/data.js, generated here from the same
 * Kotlin sources the phone uses — so the two can't drift. Regenerate with:
 *   BL_EXPORT=1 ./gradlew :app:testDebugUnitTest --tests com.blacklab.app.WebDataExportTest
 * Only public reference content is exported; nothing from anyone's workspace ever is.
 */
class WebDataExportTest {

    private val root = listOf(File("../desktop/web"), File("desktop/web")).first { it.isDirectory }
    private val out = File(root, "data.js")

    private fun hex(c: Long) = "#" + (c and 0xFFFFFF).toString(16).padStart(6, '0').uppercase()

    private fun j(v: Any?): String = when (v) {
        null -> "null"
        is String -> "\"" + v.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\""
        is Number, is Boolean -> v.toString()
        is Map<*, *> -> v.entries.joinToString(",", "{", "}") { (k, x) -> j(k.toString()) + ":" + j(x) }
        is Iterable<*> -> v.joinToString(",", "[", "]") { j(it) }
        else -> j(v.toString())
    }

    private fun version(): String {
        val gradle = listOf(File("build.gradle.kts"), File("app/build.gradle.kts")).first { it.isFile }.readText()
        return Regex("versionName = \"([^\"]+)\"").find(gradle)!!.groupValues[1]
    }

    private fun generate(): String {
        val data = linkedMapOf(
            "version" to version(),
            "palettes" to AccentPalette.entries.map { p ->
                linkedMapOf("id" to p.name, "label" to p.label,
                    "dark" to listOf(hex(p.darkAccent), hex(p.darkSecondary), hex(p.darkTertiary)),
                    "light" to listOf(hex(p.lightAccent), hex(p.lightSecondary), hex(p.lightTertiary)))
            },
            "lightStyles" to LightStyle.entries.map { s ->
                linkedMapOf("id" to s.name, "label" to s.label, "blurb" to s.blurb, "background" to hex(s.background), "card" to hex(s.card),
                    "high" to hex(s.high), "ink" to hex(s.ink), "inkSoft" to hex(s.inkSoft), "wash" to s.wash.toDouble())
            },
            "darkStyles" to com.blacklab.app.ui.theme.DarkStyle.entries.map { s ->
                linkedMapOf("id" to s.name, "label" to s.label, "blurb" to s.blurb, "background" to hex(s.background), "low" to hex(s.low), "card" to hex(s.container),
                    "high" to hex(s.high), "highest" to hex(s.highest), "line" to hex(s.outlineVariant), "wash" to s.wash.toDouble())
            },
            "corners" to com.blacklab.app.ui.theme.CornerStyle.entries.map { c -> linkedMapOf("id" to c.name, "label" to c.label, "card" to c.card, "small" to c.sm) },
            "bh" to linkedMapOf(
                "phases" to Library.CRISIS_PHASES.map { linkedMapOf("name" to it.name, "looks" to it.looks, "respond" to it.respond, "say" to it.say, "avoid" to it.avoid) },
                "tips" to Library.DEESCALATION_TIPS,
                "grounding" to Library.GROUNDING.map { linkedMapOf("name" to it.first, "how" to it.second) },
                "traumaInformed" to Library.TRAUMA_INFORMED.map { linkedMapOf("name" to it.first, "how" to it.second) },
                "resourceCategories" to Library.RESOURCE_CATEGORIES,
                "resources" to Library.RESOURCES.map { r ->
                    linkedMapOf("name" to r.name, "category" to r.category, "phone" to r.phone, "text" to r.text, "url" to r.url, "hours" to r.hours, "notes" to r.notes)
                },
                "groupCategories" to Library.GROUP_CATEGORIES,
                "groups" to Library.GROUPS.map { g ->
                    linkedMapOf("title" to g.title, "category" to g.category, "minutes" to g.minutes, "audience" to g.audience, "objective" to g.objective, "opener" to g.opener,
                        "activity" to g.activity, "discussion" to g.discussion, "closing" to g.closing, "materials" to g.materials, "adaptations" to g.adaptations)
                },
                "eoc" to Library.EOC_ITEMS.map { (area, items) -> linkedMapOf("area" to area, "items" to items.map { linkedMapOf("group" to it.group, "text" to it.text) }) },
                "riskLevels" to Library.RISK_LEVELS,
                "mitigations" to Library.MITIGATIONS,
                "checklist" to Library.SHIFT_CHECKLIST.map { linkedMapOf("phase" to it.phase, "text" to it.text) },
                "precautions" to Library.PRECAUTIONS,
            ),
        )
        return "// Generated by app/src/test/.../WebDataExportTest.kt from the app's own sources. Do not edit by hand.\n" +
            "window.BL_DATA = " + j(data) + ";\n"
    }

    @Test fun webDataMatchesTheApp() {
        val fresh = generate()
        if (System.getenv("BL_EXPORT") == "1") out.writeText(fresh)
        assertEquals("desktop/web/data.js is out of date — run with BL_EXPORT=1 to regenerate", fresh, out.takeIf { it.exists() }?.readText())
    }
}
